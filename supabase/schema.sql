-- ---------- 상품 ----------
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  name        text    not null,
  color       text,
  price       integer not null check (price >= 0),
  category    text    not null default 'unisex' check (category in ('men', 'women', 'unisex')),
  front       text,                     -- 앞면 이미지 URL
  back        text,                     -- 뒷면 이미지 URL
  tag         text,                     -- NEW, DROP 001 등
  description text,
  sort        integer not null default 0,
  active      boolean not null default true,   -- false면 쇼핑몰에서 숨김
  created_at  timestamptz not null default now()
);

-- ---------- 사이즈별 재고 ----------
create table if not exists public.product_stock (
  product_id bigint  not null references public.products (id) on delete cascade,
  size       text    not null,
  qty        integer not null default 0 check (qty >= 0),
  primary key (product_id, size)
);

-- ---------- 관리자 ----------
create table if not exists public.admins (
  email text primary key
);

create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.admins where lower(email) = lower(auth.jwt() ->> 'email'));
$$;
grant execute on function public.is_admin() to anon, authenticated;

-- ---------- 주문 ----------
create table if not exists public.orders (
  id             uuid primary key default gen_random_uuid(),
  order_no       text unique not null,          -- 토스 orderId 로도 사용
  user_id        uuid not null references auth.users (id),
  email          text,
  status         text not null default 'pending'
                 check (status in ('pending', 'paid', 'preparing', 'shipped', 'delivered', 'cancelled', 'refunded')),
  items_total    integer not null,
  shipping_fee   integer not null,
  total          integer not null,
  recipient      text not null,
  phone          text not null,
  zipcode        text not null,
  address1       text not null,
  address2       text,
  memo           text,
  payment_key    text,
  payment_method text,
  paid_at        timestamptz,
  courier        text,
  tracking_no    text,
  created_at     timestamptz not null default now()
);
create index if not exists orders_user_idx on public.orders (user_id, created_at desc);

create table if not exists public.order_items (
  id         bigint generated by default as identity primary key,
  order_id   uuid    not null references public.orders (id) on delete cascade,
  product_id bigint  references public.products (id) on delete set null,
  name       text    not null,
  color      text,
  size       text    not null,
  price      integer not null,
  qty        integer not null check (qty > 0),
  image      text
);

-- ---------- 드롭 알림 신청 ----------
create table if not exists public.waitlist (
  email      text primary key,
  source     text,
  created_at timestamptz not null default now()
);

-- ---------- 재고 차감 (결제 승인 시 서버에서만 호출) ----------
create or replace function public.decrement_stock(p_order uuid)
returns void
language plpgsql security definer set search_path = public
as $$
declare r record;
begin
  for r in select product_id, size, qty from public.order_items where order_id = p_order loop
    update public.product_stock
       set qty = qty - r.qty
     where product_id = r.product_id and size = r.size and qty >= r.qty;
    if not found then
      raise exception 'OUT_OF_STOCK %/%', r.product_id, r.size;
    end if;
  end loop;
end;
$$;
revoke execute on function public.decrement_stock(uuid) from public, anon, authenticated;
grant execute on function public.decrement_stock(uuid) to service_role;

-- ============================================================
-- 행 단위 보안(RLS)
-- ============================================================
alter table public.products      enable row level security;
alter table public.product_stock enable row level security;
alter table public.admins        enable row level security;
alter table public.orders        enable row level security;
alter table public.order_items   enable row level security;
alter table public.waitlist      enable row level security;

drop policy if exists "products read"   on public.products;
drop policy if exists "products admin"  on public.products;
create policy "products read"  on public.products for select using (active or public.is_admin());
create policy "products admin" on public.products for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "stock read"  on public.product_stock;
drop policy if exists "stock admin" on public.product_stock;
create policy "stock read"  on public.product_stock for select using (true);
create policy "stock admin" on public.product_stock for all using (public.is_admin()) with check (public.is_admin());

-- 주문은 서버(결제 함수)에서만 생성합니다. 고객은 본인 주문 조회만, 관리자는 조회·수정.
drop policy if exists "orders own"   on public.orders;
drop policy if exists "orders admin" on public.orders;
create policy "orders own"   on public.orders for select using (user_id = auth.uid() or public.is_admin());
create policy "orders admin" on public.orders for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "items own" on public.order_items;
create policy "items own" on public.order_items for select using (
  public.is_admin() or exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid())
);

drop policy if exists "waitlist insert" on public.waitlist;
drop policy if exists "waitlist admin"  on public.waitlist;
create policy "waitlist insert" on public.waitlist for insert with check (true);
create policy "waitlist admin"  on public.waitlist for select using (public.is_admin());

